/*
 * Topic: If-Else in Java
 *
 * If-else is used to perform a decision based on a condition.
 * If the condition is true, one block executes; otherwise, another block executes.
 *
 * Interview note:
 * If-else is the basic control structure used for conditional logic.
 */

public class IfElseExample {
    public static void main(String[] args) {
        int age = 18;

        if (age >= 18) {
            System.out.println("You are eligible to vote.");
        } else {
            System.out.println("You are not eligible to vote.");
        }
    }
}
