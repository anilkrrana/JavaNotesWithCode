// Definition:
// float is a primitive data type used for decimal values.
// It stores floating-point numbers with single precision and takes 4 bytes.

public class FloatExample {
    public static void main(String[] args) {
        float price = 19.99f;
        float pi = 3.14f;

        System.out.println("Float example");
        System.out.println("Price: " + price);
        System.out.println("Pi: " + pi);
    }
}
