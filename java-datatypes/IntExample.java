// Definition:
// int is the most commonly used primitive data type for whole numbers.
// It takes 4 bytes of memory and stores values from -2147483648 to 2147483647.

public class IntExample {
    public static void main(String[] args) {
        int rollNumber = 101;
        int totalMarks = 450;

        System.out.println("Int example");
        System.out.println("Roll Number: " + rollNumber);
        System.out.println("Total Marks: " + totalMarks);
    }
}
