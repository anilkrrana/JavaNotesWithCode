/*
 * Topic: Boolean in Java
 *
 * Boolean is a primitive data type used to represent true or false.
 * It is commonly used in conditions and decision-making.
 *
 * Interview note:
 * Boolean values are essential for logic, conditional statements, and validations.
 */

public class BooleanExamples {
    public static void main(String[] args) {
        boolean isJavaEasy = true;
        boolean isRaining = false;

        System.out.println("Is Java easy? " + isJavaEasy);
        System.out.println("Is it raining? " + isRaining);

        int marks = 75;
        boolean isPass = marks >= 40;
        System.out.println("Pass status: " + isPass);
    }
}
